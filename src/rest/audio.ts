import * as fs from "node:fs"
import * as path from "node:path"
import type { Request, Response } from "express"

export type AudioEpisode = {
  day: number
  title: string
  url: string
  // Seconds into the episode where the chapter's reading starts; null when
  // its spoken heading was not found, and the episode plays from the start.
  start: number | null
  // Where it ends: the last verse's closing words, or the next chapter's
  // start; null when neither was found.
  end: number | null
  // [first, last] verse, when only part of the chapter is read that day
  // (Provérbios 1:1-7).
  range?: [number, number]
  // Read in part: where the chapter's name ends in its heading, before the
  // day's verses are named ("Provérbios 3 | 1 a 4"), so a chapter heard
  // whole can say its name and skip the rest.
  titleEnd?: number
  // And where it starts: the heading's segment can begin seconds before the
  // name (the reading before, the jingle) or, heard as "1 a 7", after it.
  titleStart?: number
  // [verse, seconds into the episode] for each verse, where the reading lines
  // up well enough with the text to follow it verse by verse.
  verses?: [number, number][]
}
export type AudioIndex = Record<string, AudioEpisode[]>

/** A +365 day: its readings, then its reflection. An introduction has no readings. */
export type PlanDay = {
  day: number
  title: string
  theme: string
  priest?: string
  url: string
  duration: number
  readings: {
    bookId: string
    bookName: string
    chapter: number
    range?: [number, number]
    episode: AudioEpisode
  }[]
  reflection: number
}

// Generated by src/scripts/mais365.ts and committed; it changes only when the
// script is re-run for new episodes.
const loadData = () =>
  JSON.parse(
    fs.readFileSync(path.join(__dirname, "../../data/mais365.json"), "utf8"),
  ) as { chapters: AudioIndex; days: PlanDay[] }

export const loadAudioIndex = (): AudioIndex => loadData().chapters
export const loadPlan = (): PlanDay[] => loadData().days

export const makeAudioController =
  (index: AudioIndex) => (req: Request, res: Response) => {
    const key = `${req.params.book}/${req.params.chapter}`
    if (Object.hasOwn(index, key)) {
      return res.json({ episodes: index[key] })
    }
    res.status(404).json({ error: "Audio not found" })
  }

/**
 * The plan, light: every day without its verse timings, which only the day
 * being played needs (makePlanDayController).
 */
export const makePlanController = (plan: PlanDay[]) => {
  const days = plan.map((day) => ({
    ...day,
    readings: day.readings.map(
      ({ episode: { verses: _, ...episode }, ...reading }) => ({
        ...reading,
        episode,
      }),
    ),
  }))
  return (_req: Request, res: Response) => {
    res.json({ days })
  }
}

/** One day in full, verse timings and all ("6", or "6.5" for an introduction). */
export const makePlanDayController =
  (plan: PlanDay[]) => (req: Request, res: Response) => {
    const day = plan.find((d) => String(d.day) === req.params.day)
    if (day) return res.json(day)
    res.status(404).json({ error: "Day not found" })
  }
