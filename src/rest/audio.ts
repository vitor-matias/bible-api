import * as fs from "node:fs"
import * as path from "node:path"
import type { Request, Response } from "express"

export type AudioEpisode = {
  day: number
  title: string
  url: string
  // Seconds into the episode where the chapter's reading starts; null when
  // its spoken heading was not found, and the episode plays from the start.
  start: number | null
  // Where it ends: the last verse's closing words, or the next chapter's
  // start; null when neither was found.
  end: number | null
  // [verse, seconds into the episode] for each verse, where the reading lines
  // up well enough with the text to follow it verse by verse.
  verses?: [number, number][]
}
export type AudioIndex = Record<string, AudioEpisode[]>

// Generated by src/scripts/mais365.ts and committed; it changes only when the
// script is re-run for new episodes.
export const loadAudioIndex = (): AudioIndex =>
  JSON.parse(
    fs.readFileSync(path.join(__dirname, "../../data/mais365.json"), "utf8"),
  ).chapters

export const makeAudioController =
  (index: AudioIndex) => (req: Request, res: Response) => {
    const key = `${req.params.book}/${req.params.chapter}`
    if (Object.hasOwn(index, key)) {
      return res.json({ episodes: index[key] })
    }
    res.status(404).json({ error: "Audio not found" })
  }
